package FORlLOOP;

import java.util.Scanner;

public class SQUARE {
    static void main() {
        Scanner sc = new Scanner(System.in);

        System.out.println("INPUT: ");
        int n = sc.nextInt();



        for(int i = 1 ; i <= n ; i+=1)
        {
            System.out.println( i = i*i);
        }

    }
}
